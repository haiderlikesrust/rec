// Copies contract ABIs (contracts/out) and deployment addresses (contracts/deployments) into src/generated.ts.
import { readFileSync, readdirSync, writeFileSync, existsSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..", "..", "..");
const out = join(root, "contracts", "out");
const contracts = [
  "CookHook",
  "Launchpad",
  "LaunchToken",
  "FeeRouter",
  "OTCReserve",
  "ProtectionFund",
  "HolderAirdrop",
  "CookRouter",
];

const lower = (s) => s.replace(/^[A-Z]+(?=[A-Z][a-z])|^[A-Z]/, (m) => m.toLowerCase());
let src = "// Generated by scripts/gen.mjs. Do not edit.\n\n";
for (const name of contracts) {
  const artifact = JSON.parse(readFileSync(join(out, `${name}.sol`, `${name}.json`), "utf8"));
  src += `export const ${lower(name)}Abi = ${JSON.stringify(artifact.abi)} as const;\n\n`;
}

const depDir = join(root, "contracts", "deployments");
const deployments = {};
if (existsSync(depDir)) {
  for (const f of readdirSync(depDir).filter((f) => f.endsWith(".json"))) {
    const d = JSON.parse(readFileSync(join(depDir, f), "utf8"));
    deployments[d.chainId] = d;
  }
}
src += `/** @deprecated use otcReserveAbi */
export const oTCReserveAbi = otcReserveAbi;

`;
src += `export const deployments = ${JSON.stringify(deployments, null, 2)} as const;\n`;
writeFileSync(join(root, "packages", "shared", "src", "generated.ts"), src);
console.log(`generated ${contracts.length} ABIs, ${Object.keys(deployments).length} deployment(s)`);
